const dictionaries: Record<Exclude<Locale, 'en'>, Record<string, string>> = { rw, fr };

function normalizeKey(key: string): string {
  let normalized = sourceOverrides[key] ?? key;
  normalized = normalized.replace(/&amp;/g, '&').replace(/&apos;/g, "'").replace(/&quot;/g, '"');
  return sourceAliases[normalized.toLowerCase()] ?? normalized;
}

function interpolate(message: string, vars?: TranslateVars): string {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) => name in vars ? String(vars[name]) : match);
}

function readStoredLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'rw' || stored === 'fr') return stored;
  } catch {
    // localStorage may be unavailable in private browsing.
  }
  const browserLocale = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'en';
  if (browserLocale.startsWith('rw')) return 'rw';
  if (browserLocale.startsWith('fr')) return 'fr';
  return 'en';
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: TranslateFunction;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(readStoredLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // The selector still works for this session if storage is blocked.
    }
  }, [locale]);

  const t = useCallback<TranslateFunction>((key, vars) => {
    const normalized = normalizeKey(key);
    const message = locale === 'en' ? normalized : dictionaries[locale][normalized] ?? normalized;
    return interpolate(message, vars);
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within I18nProvider.');
  return context;
}

const kinyarwandaMonths = [
  'Mutarama', 'Gashyantare', 'Werurwe', 'Mata', 'Gicurasi', 'Kamena',
  'Nyakanga', 'Kanama', 'Nzeri', 'Ukwakira', 'Ugushyingo', 'Ukuboza'
];

function formatKinyarwandaDate(date: Date): string {
  const parts = new Intl.DateTimeFormat('en-US', {
    month: 'numeric',
    day: 'numeric',
    year: 'numeric'
  }).formatToParts(date);
  const month = Number(parts.find((part) => part.type === 'month')?.value ?? '0') - 1;
  const day = parts.find((part) => part.type === 'day')?.value ?? '';
  const year = parts.find((part) => part.type === 'year')?.value ?? '';
  if (!kinyarwandaMonths[month] || !day || !year) return date.toDateString();
  return `${day} ${kinyarwandaMonths[month]} ${year}`;
}

export function useDateFormat() {
  const { locale } = useI18n();
  return useCallback((dateString: string) => {
    const date = new Date(dateString);
    if (locale === 'rw') return formatKinyarwandaDate(date);
    return new Intl.DateTimeFormat(locale, {
      month: 'long',
      day: 'numeric',
      year: 'numeric'
    }).format(date);
  }, [locale]);
}

export function useTimeFormat() {
  const { locale } = useI18n();
  return useCallback((dateString: string) => new Intl.DateTimeFormat(locale, {
    hour: 'numeric',
    minute: '2-digit'
  }).format(new Date(dateString)), [locale]);
}

